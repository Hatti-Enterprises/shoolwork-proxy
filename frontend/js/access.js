/* ============================================================
 * access.js — Frontend access-control module
 *
 * Responsibilities:
 *   1. On app boot: check /api/access/status to see if access control is enabled
 *   2. If enabled, look for device key in localStorage
 *      - If present, verify with /api/access/check
 *      - If valid, hide gate + allow app to load
 *      - If invalid (revoked), show gate with "device revoked" message
 *      - If no device key, show gate with code entry form
 *   3. On code submit: POST /api/access/verify with code + label
 *      - If ok, store device key in localStorage, hide gate
 *      - If error, show error message in gate
 *   4. Provide apiFetch() wrapper that adds X-Device-Key header to every request
 *
 * The device key is generated by the backend (128 bits of entropy) and stored
 * in localStorage. It is NOT device-fingerprinted — any browser that knows
 * the key can use the proxy. The host can revoke any key at any time.
 * ============================================================ */

const DEVICE_KEY_STORAGE = 'shoolwork:device-key';
const DEVICE_LABEL_STORAGE = 'shoolwork:device-label';

// BACKEND_URL is set in inline script before this module loads
const BACKEND_URL = (typeof window !== 'undefined' && window.SHoolworkBackendUrl) || '';

let accessState = {
  enabled: null,    // null = unknown, true = enabled, false = disabled
  valid: null,      // null = unknown, true = key valid, false = invalid/revoked
  deviceKey: null,
  initialized: false,
};

/* ---------- Public: apiFetch wrapper ---------- */
/* Use this instead of fetch() for any /api/* request. Adds the X-Device-Key
 * header automatically when a device key is available.
 */
export function apiFetch(path, opts = {}) {
  const deviceKey = getDeviceKey();
  if (deviceKey) {
    opts.headers = opts.headers || {};
    if (opts.headers instanceof Headers) {
      opts.headers.set('X-Device-Key', deviceKey);
    } else {
      opts.headers['X-Device-Key'] = deviceKey;
    }
  }
  return fetch((BACKEND_URL || '') + path, opts);
}

/* ---------- Device key management ---------- */

export function getDeviceKey() {
  try { return localStorage.getItem(DEVICE_KEY_STORAGE); } catch { return null; }
}

export function getDeviceLabel() {
  try { return localStorage.getItem(DEVICE_LABEL_STORAGE) || ''; } catch { return ''; }
}

export function setDeviceKey(key, label) {
  try {
    localStorage.setItem(DEVICE_KEY_STORAGE, key);
    if (label) localStorage.setItem(DEVICE_LABEL_STORAGE, label);
  } catch { /* private mode */ }
}

export function clearDeviceKey() {
  try {
    localStorage.removeItem(DEVICE_KEY_STORAGE);
    localStorage.removeItem(DEVICE_LABEL_STORAGE);
  } catch { /* private mode */ }
}

/* ---------- Status check ---------- */

export async function checkAccessStatus() {
  try {
    const res = await apiFetch('/api/access/status', { credentials: 'include' });
    if (!res.ok) return { enabled: false, devices: { active: 0, revoked: 0, total: 0 } };
    const data = await res.json();
    return data;
  } catch {
    return { enabled: false, devices: { active: 0, revoked: 0, total: 0 } };
  }
}

export async function verifyDeviceKey() {
  const key = getDeviceKey();
  if (!key) return false;
  try {
    const res = await apiFetch('/api/access/check', {
      method: 'POST',
      credentials: 'include',
    });
    if (!res.ok) return false;
    const data = await res.json();
    return !!data.valid;
  } catch {
    return false;
  }
}

/* ---------- Code verification ---------- */

export async function verifyCode(code, label) {
  try {
    const res = await apiFetch('/api/access/verify', {
      method: 'POST',
      credentials: 'include',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ code, label }),
    });
    const data = await res.json();
    if (data.ok && data.deviceKey) {
      setDeviceKey(data.deviceKey, label);
      accessState.deviceKey = data.deviceKey;
      accessState.valid = true;
      return { ok: true };
    }
    return { ok: false, error: data.error || 'Verification failed' };
  } catch (e) {
    return { ok: false, error: e.message };
  }
}

/* ---------- Initialize ---------- */

export async function initAccess() {
  if (accessState.initialized) return accessState;
  accessState.initialized = true;

  const status = await checkAccessStatus();
  accessState.enabled = status.enabled;

  if (!status.enabled) {
    accessState.valid = true;  // No access control — always valid
    applyGateState();
    return accessState;
  }

  // Access control enabled — check existing device key
  const key = getDeviceKey();
  if (!key) {
    accessState.valid = false;
    applyGateState();
    return accessState;
  }

  accessState.deviceKey = key;
  const valid = await verifyDeviceKey();
  accessState.valid = valid;
  applyGateState();
  return accessState;
}

export function getAccessState() {
  return accessState;
}

export function isAccessGranted() {
  if (!accessState.enabled) return true;  // Disabled = always granted
  return accessState.valid === true;
}

/* ---------- Gate UI ---------- */

function applyGateState() {
  const gate = document.getElementById('accessGate');
  if (!gate) return;

  if (!accessState.enabled || accessState.valid === true) {
    gate.hidden = true;
    document.body.style.overflow = '';
    return;
  }

  // Show the gate
  gate.hidden = false;
  document.body.style.overflow = 'hidden';

  const titleEl = document.getElementById('accessGateTitle');
  const subtitleEl = document.getElementById('accessGateSubtitle');
  const hintEl = document.getElementById('accessGateHint');

  if (accessState.valid === false && getDeviceKey()) {
    // Device key present but invalid (revoked)
    if (titleEl) titleEl.textContent = 'Device Revoked';
    if (subtitleEl) subtitleEl.textContent = 'Your device key has been revoked by the host. Enter a new invite code to regain access.';
    if (hintEl) {
      hintEl.textContent = '';
      hintEl.className = 'access-gate__hint';
    }
    // Clear the bad device key so they can enter a new code
    clearDeviceKey();
  } else {
    // No device key at all — first visit
    if (titleEl) titleEl.textContent = 'Access Required';
    if (subtitleEl) subtitleEl.textContent = 'Enter your invite code to continue. Codes are single-use — once claimed, the code is useless to anyone else.';
    if (hintEl) {
      hintEl.textContent = '';
      hintEl.className = 'access-gate__hint';
    }
  }

  // Focus the input
  const input = document.getElementById('accessCodeInput');
  if (input) setTimeout(() => input.focus(), 100);

  // Wire up form submit (idempotent — safe to call multiple times)
  const form = document.getElementById('accessForm');
  if (form && !form.dataset.wired) {
    form.dataset.wired = '1';
    form.addEventListener('submit', handleAccessSubmit);
  }
}

async function handleAccessSubmit(e) {
  e.preventDefault();
  const input = document.getElementById('accessCodeInput');
  const hint = document.getElementById('accessGateHint');
  const submitBtn = document.querySelector('.access-gate__submit');
  if (!input) return;

  const code = input.value.trim();
  if (!code) {
    if (hint) {
      hint.textContent = 'Please enter a code.';
      hint.className = 'access-gate__hint is-error';
    }
    return;
  }

  if (submitBtn) {
    submitBtn.disabled = true;
    submitBtn.textContent = 'Verifying…';
  }
  if (hint) {
    hint.textContent = 'Verifying code…';
    hint.className = 'access-gate__hint';
  }

  // Capture a label from a prompt (optional) — uses the cloak title if set,
  // otherwise asks the user. We keep it simple: just use a timestamp.
  const label = `device-${new Date().toISOString().slice(0, 10)}`;

  const result = await verifyCode(code, label);
  if (result.ok) {
    if (hint) {
      hint.textContent = 'Access granted. Loading…';
      hint.className = 'access-gate__hint is-success';
    }
    accessState.valid = true;
    setTimeout(() => {
      applyGateState();
      // Reload to re-init the app with the new device key in headers
      location.reload();
    }, 600);
  } else {
    if (hint) {
      hint.textContent = result.error || 'Verification failed.';
      hint.className = 'access-gate__hint is-error';
    }
    if (submitBtn) {
      submitBtn.disabled = false;
      submitBtn.textContent = 'Unlock';
    }
    input.select();
  }
}

window.__shoolworkAccess = {
  apiFetch,
  getDeviceKey,
  setDeviceKey,
  clearDeviceKey,
  initAccess,
  isAccessGranted,
  getAccessState,
  verifyCode,
};
